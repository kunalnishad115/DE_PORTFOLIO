import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
 await page.goto('http://127.0.0.1:5174', { waitUntil: 'networkidle' });
 await page.waitForSelector('.visitor-pass[data-renderer="webgl"]');
 await page.waitForTimeout(2500);
 const handle = page.locator('.visitor-drag-handle');
 const canvas = page.locator('.visitor-overlay');
 const box = await handle.boundingBox();
 assert.ok(box && box.width > 50);
 await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
 await page.mouse.down();
 assert.equal(await canvas.getAttribute('data-dragging'), 'true');
 await page.mouse.move(box.x + box.width / 2 + 150, box.y + box.height / 2 + 180, { steps: 20 });
 await page.mouse.up();
 assert.equal(await canvas.getAttribute('data-dragging'), 'false');
 await page.waitForTimeout(2500);
 assert.ok((await canvas.getAttribute('data-position')).split(',').every(n => Number.isFinite(Number(n))));
 await page.locator('#motion-toggle').click();
 await page.locator('#motion-toggle').click();
 const rest = await handle.boundingBox();
 await page.keyboard.down('Shift');
 await page.mouse.move(rest.x + rest.width / 2, rest.y + rest.height / 2);
 await page.mouse.down();
 assert.equal(await canvas.getAttribute('data-dragging'), 'true');
 await page.mouse.move(rest.x + rest.width / 2 + 240, rest.y + rest.height / 2, { steps: 40 });
 await page.mouse.up();
 await page.keyboard.up('Shift');
 await page.waitForTimeout(700);
 await handle.focus();
 await page.keyboard.press('ArrowRight');
 await page.keyboard.press('Enter');
 await page.waitForTimeout(2200);
 await page.screenshot({ path: 'test-results/visitor-card-updated.png' });
 assert.deepEqual(errors, []);
 console.log('PASS: WebGL, stretch and release, finite return, full-turn drag, keyboard spin, replay, and browser errors.');
} finally { await browser.close(); }
